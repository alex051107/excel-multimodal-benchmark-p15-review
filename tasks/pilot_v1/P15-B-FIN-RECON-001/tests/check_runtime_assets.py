#!/usr/bin/env python3
"""Fail closed when verifier-context DEV assets drift from the visible task sources."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

TESTS = Path(__file__).resolve().parent
TASK = TESTS.parent
DEV = TESTS / "dev"


def same(relative_source: str, relative_copy: str) -> None:
    source, copy = TASK / relative_source, TASK / relative_copy
    assert source.is_file(), f"missing source: {source}"
    assert copy.is_file(), f"missing verifier copy: {copy}"
    assert source.read_bytes() == copy.read_bytes(), f"verifier copy drift: {relative_copy}"


contract = json.loads((TESTS / "private_contract.json").read_text())
assert contract["split"] == "dev"
assert contract["input_files_dir"] == "tests/dev/data/input_files"
assert contract["oracle"] == "tests/dev/metadata/oracle_recompute.py"
assert contract["perturbations_file"] == "tests/dev/metadata/perturbations.json"

same("metadata/oracle_recompute.py", "tests/dev/metadata/oracle_recompute.py")
same("metadata/perturbations.json", "tests/dev/metadata/perturbations.json")
source_csv = sorted(path.name for path in (TASK / "data/input_files").glob("*.csv"))
copy_csv = sorted(path.name for path in (DEV / "data/input_files").glob("*.csv"))
assert source_csv == copy_csv, "DEV source snapshot file set drift"
for name in source_csv:
    same(f"data/input_files/{name}", f"tests/dev/data/input_files/{name}")

for key in ("input_files_dir", "oracle", "perturbations_file"):
    relative = Path(contract[key])
    assert relative.parts[0] == "tests", f"{key} escapes verifier Docker context"
    assert (TASK / relative).exists(), f"local verifier path missing: {relative}"
    assert (TESTS / Path(*relative.parts[1:])).exists(), f"/tests projection missing: {relative}"

confirm = json.loads((TESTS / "confirm/contract.json").read_text())
assert confirm["input_files_dir"] == "tests/confirm/input_files"
assert confirm["oracle"] == "tests/confirm/oracle_recompute.py"

copy_lines = [line.strip() for line in (TESTS / "Dockerfile").read_text().splitlines() if line.strip().startswith("COPY ")]
assert copy_lines == ["COPY . /tests"], "verifier Dockerfile must copy only the tests context"
assert (TESTS / ".dockerignore").read_text().splitlines() == ["__pycache__/", "*.py[cod]"], "verifier context must exclude generated bytecode"
agent_copy_lines = [line.strip() for line in (TASK / "environment/Dockerfile").read_text().splitlines() if line.strip().startswith("COPY ")]
assert agent_copy_lines == ["COPY input/ /app/input/"], "Agent image must not receive tests or verifier-private assets"

spec = importlib.util.spec_from_file_location("dev_oracle", TASK / contract["oracle"])
module = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(module)
truth = module.recompute()
assert isinstance(truth, dict) and truth, "DEV oracle returned no truth"

if contract["task_id"] == "P15-B-PUBLIC-PIVOT-001":
    assert confirm["status"] == "TASK_INVALID"
    assert confirm["blocker"] == "PENDING_EXTERNAL_WINDOWS_EXCEL"
    assert confirm["reference_workbook"] is None
    assert not (TESTS / "confirm/reference.xlsx").exists()

print(json.dumps({"task_id": contract["task_id"], "status": "PASS", "synced_csv": source_csv, "verifier_copy": copy_lines[0], "agent_copy": agent_copy_lines[0]}, sort_keys=True))
