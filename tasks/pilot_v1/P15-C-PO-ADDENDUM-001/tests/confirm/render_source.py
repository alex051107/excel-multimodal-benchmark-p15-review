#!/usr/bin/env python3
"""Render the distinct verifier-private confirm PO addendum source."""
import json
from pathlib import Path
from reportlab.lib.colors import HexColor, black, white
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parent
truth = json.loads((ROOT / "truth.json").read_text(encoding="utf-8"))
output = ROOT / "input_files" / truth["document"]["filename"]
navy = HexColor("#203B55")
accent = HexColor("#E6EEF5")

def header(pdf, page):
    pdf.setFillColor(navy)
    pdf.rect(0, 724, 612, 68, fill=1, stroke=0)
    pdf.setFillColor(white)
    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawString(42, 756, f"Purchase Order Addendum {truth['headers']['addendum']}")
    pdf.setFont("Helvetica", 10)
    pdf.drawRightString(570, 756, f"PO {truth['headers']['po_id']}")
    pdf.drawRightString(570, 740, f"Page {page} of 2")
    pdf.setFillColor(black)

pdf = canvas.Canvas(str(output), pagesize=letter)
pdf.setTitle(f"Confirm addendum {truth['headers']['po_id']}")
header(pdf, 1)
pdf.setFont("Helvetica", 11)
pdf.drawString(42, 690, f"Reason: {truth['headers']['reason']}")
pdf.drawRightString(570, 690, f"Effective deadline: {truth['headers']['effective_deadline']}")
pdf.drawString(42, 670, f"Currency: {truth['headers']['currency']}")
pdf.setFillColor(accent)
pdf.rect(42, 620, 528, 28, fill=1, stroke=0)
pdf.setFillColor(black)
pdf.setFont("Helvetica-Bold", 11)
pdf.drawString(54, 630, "Schedule changes on this page")
pdf.setFont("Helvetica-Bold", 10)
pdf.drawString(54, 586, "PO-11 - Pump skids")
pdf.setFont("Helvetica", 10)
pdf.drawString(70, 566, "Original: 12 each at $310.00 each")
pdf.drawString(70, 548, "Revised: 14 each at $310.00 each")
pdf.drawString(70, 530, "Change type: quantity changed")
pdf.setFont("Helvetica-Bold", 10)
pdf.drawString(54, 486, "PO-13 - Conduit bundles")
pdf.setFont("Helvetica", 10)
pdf.drawString(70, 466, "Original: 40 units at $48.00 per unit")
pdf.drawString(70, 448, "Revised: 40 units at $53.00 per unit")
pdf.drawString(70, 430, "Change type: unit price changed")
pdf.setFillColor(accent)
pdf.rect(42, 330, 528, 62, fill=1, stroke=0)
pdf.setFillColor(black)
pdf.setFont("Helvetica-Bold", 10)
pdf.drawString(56, 368, "Change locality")
pdf.setFont("Helvetica", 10)
pdf.drawString(56, 348, "PO-14 Safety barriers remains unchanged: 6 each at $75.00 each.")
pdf.drawString(56, 334, "No other base-schedule line is revised by this addendum.")
pdf.setFont("Helvetica-Oblique", 9)
pdf.drawString(42, 56, "Insertion details continue on page 2.")
pdf.showPage()

header(pdf, 2)
pdf.setFillColor(accent)
pdf.rect(42, 640, 528, 28, fill=1, stroke=0)
pdf.setFillColor(black)
pdf.setFont("Helvetica-Bold", 11)
pdf.drawString(54, 650, "Inserted schedule line")
pdf.setFont("Helvetica-Bold", 10)
pdf.drawString(54, 608, "PO-12 - Factory acceptance test")
pdf.setFont("Helvetica", 10)
pdf.drawString(70, 586, "Original: not present in the base schedule")
pdf.drawString(70, 568, "Revised: 1 visit at $520.00 per visit")
pdf.drawString(70, 550, "Change type: inserted")
pdf.setFont("Helvetica-Bold", 11)
pdf.drawString(42, 484, "Authorization")
pdf.setFont("Helvetica", 10)
pdf.drawString(42, 462, f"Apply these changes to PO {truth['headers']['po_id']} by {truth['headers']['effective_deadline']}.")
pdf.drawString(42, 444, "Retain all unlisted base-schedule rows without alteration.")
pdf.drawString(42, 426, "Maintain a revision log with source page references.")
pdf.setFillColor(accent)
pdf.rect(42, 330, 528, 54, fill=1, stroke=0)
pdf.setFillColor(black)
pdf.drawString(56, 358, f"Addendum reason: {truth['headers']['reason']}")
pdf.drawString(56, 340, f"Document currency: {truth['headers']['currency']}")
pdf.save()
print(output)
